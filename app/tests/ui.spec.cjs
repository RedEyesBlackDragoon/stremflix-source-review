const {test,expect}=require('@playwright/test');
test('first run, administrator management, profile scope, feedback controls, mobile and remote navigation',async({page})=>{
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto('/');
  await page.getByRole('button',{name:'Set Up Household',exact:true}).click();
  await page.getByLabel('Server enrollment token').fill('synthetic-ui-enrollment-token-000000000000');
  await page.getByLabel('Household name').fill('Synthetic UI home');
  await page.getByLabel('Administrator password (12+ characters)').fill('synthetic-ui-password-123');
  await page.getByRole('button',{name:'Create household',exact:true}).click();
  await expect(page.getByRole('heading',{name:"Who's watching?"})).toBeVisible();
  const adminSession=await page.evaluate(()=>JSON.parse(sessionStorage.getItem('household-session')));
  expect((await page.request.post('/__test__/catalog',{headers:{Authorization:`Bearer ${adminSession.access_token}`}})).ok()).toBe(true);
  await page.getByRole('button',{name:'Add Profile',exact:true}).click();
  await page.getByLabel('Display name').fill('Synthetic A');
  await page.getByRole('button',{name:'Create profile',exact:true}).click();
  await expect(page.getByRole('button',{name:'Manage Synthetic A'})).toBeVisible();
  await page.getByRole('button',{name:'Add Profile',exact:true}).click();
  await page.getByLabel('Display name').fill('Synthetic B');
  await page.getByRole('button',{name:'Create profile',exact:true}).click();
  await page.getByRole('button',{name:'Manage Synthetic B'}).click();
  await page.getByRole('button',{name:'Import Netflix history',exact:true}).click();
  await page.getByLabel('Netflix CSV',{exact:true}).setInputFiles({name:'synthetic.csv',mimeType:'text/csv',buffer:Buffer.from('Title,Date\nSynthetic Orbit Example,10/01/2026\n')});
  await page.getByRole('button',{name:'Import CSV',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Review Netflix import',exact:true})).toBeVisible();
  await expect(page.getByRole('heading',{name:'Synthetic Orbit Example',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Skip',exact:true}).click();
  await expect(page.getByText('skipped: 1',{exact:false})).toBeVisible();
  await page.getByRole('button',{name:"Who's watching?",exact:true}).click();
  await page.getByRole('button',{name:'Synthetic A',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Make tonight yours.'})).toBeVisible();
  const session=await page.evaluate(()=>JSON.parse(sessionStorage.getItem('household-session')));
  expect(session.admin).toBe(false);
  await page.getByRole('button',{name:'Synthetic Orbit Example, 2024, Age 8+'}).first().click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.getByRole('button',{name:'Like',exact:true}).click();
  await expect(page.getByRole('button',{name:'Undo Like',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Close',exact:true}).click();
  await page.locator('nav').getByRole('button',{name:'Search',exact:true}).click();
  await page.getByLabel('Search titles').fill('no such title');
  await page.getByLabel('Search titles').focus();
  await page.keyboard.press('ArrowDown');
  await expect(page.getByLabel('Search titles')).not.toBeFocused();
  await page.locator('main').getByRole('button',{name:'Search',exact:true}).click();
  await expect(page.getByText('No matches. Try a shorter title or change your filters.')).toBeVisible();
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button',{name:'Home',exact:true}).click();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:'../docs/household/mobile-ui.png',fullPage:true});
  await page.setViewportSize({width:1920,height:1080});
  await page.getByRole('button',{name:'Home',exact:true}).focus();
  await page.keyboard.press('ArrowRight');
  await expect(page.getByRole('button',{name:'Search',exact:true})).toBeFocused();
  await page.keyboard.press('Enter');
  await expect(page.getByRole('heading',{name:'Find your next story'})).toBeVisible();
  await page.screenshot({path:'../docs/household/desktop-ui.png',fullPage:true});
  expect(errors).toEqual([]);
});
